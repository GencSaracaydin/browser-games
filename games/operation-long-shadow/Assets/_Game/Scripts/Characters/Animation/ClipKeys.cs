namespace LongShadow.Characters.Animation
{
    /// <summary>
    /// Logical clip slots of the WP05 controllers. The editor <c>ClipCatalog</c> maps each key to an ordered list of
    /// candidate clips across the sources (Meshy rifle clips, HY-Motion signals, Rocketbox, Quaternius UAL1/UAL2, Unity
    /// SAC, finger poses) and falls back to a generated placeholder clip when none has landed yet.
    /// </summary>
    public static class ClipKeys
    {
        // ---- base locomotion (in place, speed-matched)
        public const string Idle = "Idle";
        public const string TurnLeft = "TurnLeft";
        public const string TurnRight = "TurnRight";
        public const string WalkFwd = "WalkFwd";
        public const string WalkBack = "WalkBack";
        public const string WalkLeft = "WalkLeft";
        public const string WalkRight = "WalkRight";
        public const string JogFwd = "JogFwd";
        public const string JogLeft = "JogLeft";
        public const string JogRight = "JogRight";
        public const string JogBack = "JogBack";
        public const string Sprint = "Sprint";
        public const string CrouchIdle = "CrouchIdle";
        public const string CrouchFwd = "CrouchFwd";
        public const string CrouchBack = "CrouchBack";
        public const string CrouchLeft = "CrouchLeft";
        public const string CrouchRight = "CrouchRight";
        public const string PerchIdle = "PerchIdle";
        public const string Airborne = "Airborne";

        // ---- shadow proxy (AC_ShadowProxy, D19)
        public const string AimIdle = "AimIdle";
        public const string AimWalk = "AimWalk";

        // ---- arms layer (mask AM_Arms)
        public const string ArmsAim = "ArmsAim";
        public const string ArmsLowReady = "ArmsLowReady";
        public const string ArmsPistol = "ArmsPistol";
        public const string ArmsPistolAim = "ArmsPistolAim";
        public const string ArmsLauncher = "ArmsLauncher";
        public const string Reload = "Reload";
        public const string ThrowArms = "ThrowArms";
        public const string SignalArms = "SignalArms";
        public const string FistHoldArms = "FistHoldArms";
        public const string PhoneArms = "PhoneArms";
        public const string InteractArms = "InteractArms";
        public const string CameraArms = "CameraArms";
        public const string WatchArms = "WatchArms";
        public const string OneFingerArms = "OneFingerArms";
        public const string WaveArms = "WaveArms";

        // ---- additive hits (mask AM_UpperBody)
        public const string HitFront = "HitFront";
        public const string HitBack = "HitBack";
        public const string HitLeft = "HitLeft";
        public const string HitRight = "HitRight";

        // ---- deaths
        public const string DeathBackward = "DeathBackward";
        public const string DeathForward = "DeathForward";
        public const string DeathBlown = "DeathBlown";
        public const string DeathCrumple = "DeathCrumple";
        public const string DeathHead = "DeathHead";

        // ---- full-body actions
        public const string KneelWork = "KneelWork";
        public const string PlantCharge = "PlantCharge";
        public const string ThrowFull = "ThrowFull";
        public const string Kick = "Kick";
        public const string Vault = "Vault";
        public const string Climb = "Climb";
        public const string Drop = "Drop";
        public const string Ladder = "Ladder";
        public const string Carry = "Carry";
        public const string SitChair = "SitChair";
        public const string SitTalk = "SitTalk";
        public const string SitNervous = "SitNervous";
        public const string SitArmsCrossed = "SitArmsCrossed";
        public const string Prone = "Prone";
        public const string LookAround = "LookAround";
        public const string Kneel = "Kneel";
        public const string StandIdle = "StandIdle";
        public const string StandTalk = "StandTalk";
        public const string BoothWalk = "BoothWalk";

        // ---- first-person arms
        public const string FPArmsBase = "FPArmsBase";

        // ---- finger poses (content A_Pose_* FBX, else generated by FingerPoseAuthoring)
        public const string PoseRelaxed = "A_Pose_Relaxed";
        public const string PoseRifleGrip = "A_Pose_RifleGrip";
        public const string PosePistolGrip = "A_Pose_PistolGrip";
        public const string PoseFist = "A_Pose_Fist";
        public const string PoseFlat = "A_Pose_FlatHands";

        /// <summary>Finger pose clip name for a <see cref="HandPose"/>.</summary>
        public static string ForHandPose(HandPose pose)
        {
            switch (pose)
            {
                case HandPose.RifleGrip: return PoseRifleGrip;
                case HandPose.PistolGrip: return PosePistolGrip;
                case HandPose.Fist: return PoseFist;
                case HandPose.Flat: return PoseFlat;
                default: return PoseRelaxed;
            }
        }

        /// <summary>Death clip key for a death index (<see cref="CharacterAnimIds.DeathBackward"/>...).</summary>
        public static string ForDeath(int deathIndex)
        {
            switch (deathIndex)
            {
                case CharacterAnimIds.DeathForward: return DeathForward;
                case CharacterAnimIds.DeathBlown: return DeathBlown;
                case CharacterAnimIds.DeathCrumple: return DeathCrumple;
                case CharacterAnimIds.DeathHead: return DeathHead;
                default: return DeathBackward;
            }
        }

        /// <summary>Hit clip key for a hit direction (<see cref="CharacterAnimIds.HitFront"/>...).</summary>
        public static string ForHitDir(int hitDir)
        {
            switch (hitDir)
            {
                case CharacterAnimIds.HitBack: return HitBack;
                case CharacterAnimIds.HitLeft: return HitLeft;
                case CharacterAnimIds.HitRight: return HitRight;
                default: return HitFront;
            }
        }
    }
}
