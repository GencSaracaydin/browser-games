        {
            // Houses along Sunset Lane (GDD §6.5 A5): the lane runs from (181, 0, 238) at azimuth 258° to (120, 0, 225), 5 m
            // wide; houses face it on both sides and are rotated with it (yaw −12°), so nothing stands in its line.
            var dir = new Vector3(Mathf.Sin(WorldConst.SunAzimuth * Mathf.Deg2Rad), 0f, Mathf.Cos(WorldConst.SunAzimuth * Mathf.Deg2Rad));
            var north = new Vector3(-dir.z, 0f, dir.x);
            if (north.z < 0f) north = -north;
