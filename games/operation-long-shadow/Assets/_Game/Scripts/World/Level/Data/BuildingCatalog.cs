        /// <summary>
        /// For every party side, the height of the tallest neighbour that touches it (so only the wall above it is built).
        /// Rotated buildings are skipped (their neighbours are rotated too and touch along the lane only).
        /// </summary>
        public static void ResolvePartyHeights(IList<BuildingSpec> list)
        {
            foreach (var a in list)
            {
                if (!Mathf.Approximately(a.Yaw, 0f)) continue;
                for (var side = 0; side < 4; side++)
                {
                    if (a.Facades[side] != FacadeKind.Party) continue;
                    var best = 0f;
                    foreach (var b in list)
                    {
                        if (ReferenceEquals(a, b) || !Mathf.Approximately(b.Yaw, 0f)) continue;
                        if (!Touches(a.Footprint, b.Footprint, side)) continue;
                        best = Mathf.Max(best, b.TopY - a.BaseY);
                    }
                    a.PartyHeights[side] = best;
                }
            }
        }

        /// <summary>True if <paramref name="b"/> touches side <paramref name="side"/> of <paramref name="a"/> (within 0.7 m, overlapping along it).</summary>
        public static bool Touches(AreaRect a, AreaRect b, int side)
        {
            const float tol = 0.7f;
            switch (side)
            {
                case 0: return Mathf.Abs(b.Z1 - a.Z0) < tol && b.X1 > a.X0 + 0.5f && b.X0 < a.X1 - 0.5f;
                case 1: return Mathf.Abs(b.X0 - a.X1) < tol && b.Z1 > a.Z0 + 0.5f && b.Z0 < a.Z1 - 0.5f;
