        private static List<BuildingSpec> s_all;

        /// <summary>Every catalogued building (not the far-only housing).</summary>
        public static IReadOnlyList<BuildingSpec> All => s_all ?? (s_all = Build());

        /// <summary>Buildings of one section scene.</summary>
        public static IEnumerable<BuildingSpec> Of(SectionId section)
        {
            foreach (var b in All)
                if (b.Section == section) yield return b;
        }

        /// <summary>A building by id, or null.</summary>
        public static BuildingSpec Get(string id)
        {
            foreach (var b in All)
                if (b.Id == id) return b;
            return null;
        }

