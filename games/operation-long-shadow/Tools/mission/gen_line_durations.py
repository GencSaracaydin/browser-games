#!/usr/bin/env python3
"""Generates Staging/Mission/Data/LineDurations.cs from the WP06 VO envelopes.

Fallback durations (seconds) for every DIALOGUE.json line, used by the MissionDirector only when no IVOService is
registered or the VO service reports 0 for a line (lines then still take their real time, so beat pacing and the
MID-A schedule stay intact), and by the EditMode fake world. Source: the shipped clips' envelope JSONs
(RawAssets/audio/ready/Assets/_Game/Audio/Envelopes/VO_<id>.json, WP06_VO), longest chain per line. Lines without an
envelope get a word-count estimate (2.6 words/s + 0.4 s). D039 also exports the Clockmaker token onsets.

Usage (project root):  python3 Tools/mission/gen_line_durations.py [--check]
"""
import glob
import json
import os
import re
import sys

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), "..", ".."))
ENV_GLOB = os.path.join(ROOT, "RawAssets", "audio", "ready", "Assets", "_Game", "Audio", "Envelopes", "VO_*.json")
DIALOGUE = os.path.join(ROOT, "Docs", "DIALOGUE.json")
OUT = os.path.join(ROOT, "Staging", "Mission", "Data", "LineDurations.cs")


def main():
    check = "--check" in sys.argv
    lines = json.load(open(DIALOGUE, encoding="utf-8"))
    measured = {}
    onsets = {}
    for path in sorted(glob.glob(ENV_GLOB)):
        e = json.load(open(path, encoding="utf-8"))
        durs = [c["duration_s"] for c in e.get("clips", {}).values() if "duration_s" in c]
        if durs:
            measured[e["id"]] = max(durs)
        if e.get("token_onsets_s"):
            onsets[e["id"]] = [(t["token"], t["t"]) for t in e["token_onsets_s"]]
    rows = []
    for l in lines:
        lid = l["id"]
        if lid in measured:
            rows.append((lid, round(measured[lid], 3), "measured"))
        else:
            words = len(re.findall(r"[A-Za-z0-9'-]+", l.get("text", "")))
            rows.append((lid, round(words / 2.6 + 0.4, 2), "estimate"))
    out = []
    out.append("// <auto-generated> by Tools/mission/gen_line_durations.py from the WP06 VO envelopes. Do not edit by hand.")
    out.append("using System.Collections.Generic;")
    out.append("")
    out.append("namespace LongShadow.Mission.Data")
    out.append("{")
    out.append("    /// <summary>")
    out.append("    /// Fallback line durations in seconds (longest shipped chain per DIALOGUE.json line, measured from the WP06 VO")
    out.append("    /// envelopes; " + str(sum(1 for r in rows if r[2] == 'estimate')) + " of " + str(len(rows)) + " lines are word-count estimates). Used when no IVOService is")
    out.append("    /// registered or it reports 0, so beat pacing and MID-A keep their real timing, and by the EditMode fake world.")
    out.append("    /// </summary>")
    out.append("    public static class LineDurations")
    out.append("    {")
    out.append("        /// <summary>Duration used for a line that is not in the table.</summary>")
    out.append("        public const float Unknown = 2.5f;")
    out.append("")
    out.append("        private static readonly string[] s_ids =")
    out.append("        {")
    for i in range(0, len(rows), 8):
        out.append("            " + " ".join('"%s",' % r[0] for r in rows[i:i + 8]))
    out.append("        };")
    out.append("")
    out.append("        private static readonly float[] s_seconds =")
    out.append("        {")
    for i in range(0, len(rows), 8):
        out.append("            " + " ".join("%sf," % repr(float(r[1])) for r in rows[i:i + 8]))
    out.append("        };")
    out.append("")
    d39 = onsets.get("D039", [])
    out.append("        /// <summary>D039 token onsets in seconds from the start of the clip (Clockmaker splice grid, 0.9 s).</summary>")
    out.append("        public static readonly float[] D039TokenOnsets = { " + " ".join("%sf," % repr(float(t)) for _, t in d39) + " };")
    out.append("")
    out.append("        /// <summary>D039 tokens matching <see cref=\"D039TokenOnsets\"/>.</summary>")
    out.append("        public static readonly string[] D039Tokens = { " + " ".join('"%s",' % k for k, _ in d39) + " };")
    out.append("")
    out.append("        private static Dictionary<string, float> s_map;")
    out.append("")
    out.append("        /// <summary>Number of lines in the table.</summary>")
    out.append("        public static int Count => s_ids.Length;")
    out.append("")
    out.append("        /// <summary>Every line id in the table (DIALOGUE.json order).</summary>")
    out.append("        public static IReadOnlyList<string> Ids => s_ids;")
    out.append("")
    out.append("        /// <summary>Seconds for a line (<see cref=\"Unknown\"/> if not listed).</summary>")
    out.append("        public static float Of(string lineId)")
    out.append("        {")
    out.append("            if (string.IsNullOrEmpty(lineId)) return Unknown;")
    out.append("            if (s_map == null)")
    out.append("            {")
    out.append("                var m = new Dictionary<string, float>(s_ids.Length);")
    out.append("                for (var i = 0; i < s_ids.Length; i++) m[s_ids[i]] = s_seconds[i];")
    out.append("                s_map = m;")
    out.append("            }")
    out.append("            return s_map.TryGetValue(lineId, out var s) ? s : Unknown;")
    out.append("        }")
    out.append("")
    out.append("        /// <summary>True if the line is listed.</summary>")
    out.append("        public static bool Contains(string lineId)")
    out.append("        {")
    out.append("            Of(lineId);")
    out.append("            return lineId != null && s_map.ContainsKey(lineId);")
    out.append("        }")
    out.append("    }")
    out.append("}")
    text = "\n".join(out) + "\n"
    if check:
        cur = open(OUT, encoding="utf-8").read() if os.path.exists(OUT) else ""
        print("up to date" if cur == text else "STALE")
        sys.exit(0 if cur == text else 1)
    os.makedirs(os.path.dirname(OUT), exist_ok=True)
    with open(OUT, "w", encoding="utf-8") as f:
        f.write(text)
    print("wrote %s (%d lines, %d measured)" % (os.path.relpath(OUT, ROOT), len(rows), sum(1 for r in rows if r[2] == "measured")))


if __name__ == "__main__":
    main()
