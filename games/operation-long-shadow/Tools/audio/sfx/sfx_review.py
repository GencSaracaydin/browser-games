"""Writes the WP06_SFX section of Docs/AUDIO_REVIEW.md (between <!-- SFX:BEGIN --> and <!-- SFX:END -->) from the
pipeline's own measurements: qa_report.json (re-measured files on disk), build_report_sfx.json (selection, levels,
layer balance), scan.json (machine-listen answers and guardrails) and the fal ledger. The VO section is not touched.

usage: python sfx_review.py          (run qa_report.py first)
"""
from __future__ import annotations

import collections
import json
import pathlib
import re

ROOT = pathlib.Path("/Users/gencsaracaydin/Documents/fun/fun-unity")
QA = ROOT / "RawAssets/audio/sfx/_qa"
DOC = ROOT / "Docs/AUDIO_REVIEW.md"
LEDGER = ROOT / "Tools/fal/ledger.jsonl"
MANIFEST = ROOT / "Docs/ASSET_MANIFEST.json"
BEGIN, END = "<!-- SFX:BEGIN -->", "<!-- SFX:END -->"

GUARD_Q = {"ambience": ["voices/speech/shouting", "singing/humming/chanting", "music/instruments", "bells/chimes",
                        "call to prayer / religious", "horns/sirens/modern traffic"],
           "music": ["vocals/singing/spoken words", "chanting/religious music", "church bells", "regional/ethnic scale or instrument",
                     "fades out/ends inside the clip"]}


def spend():
    rows = {}
    for line in LEDGER.read_text().splitlines():
        if line.strip():
            r = json.loads(line)
            rows.setdefault(r["uid"], {}).update(r)
    w = [r for r in rows.values() if r.get("wp") == "WP06SFX" and r.get("status") != "not_submitted"]
    by = collections.Counter()
    for r in w:
        by[r["endpoint"]] += float(r.get("est_usd", 0))
    return sum(by.values()), by, len(w)


def fmt(v, nd=1):
    if v is None:
        return "–"
    if isinstance(v, float):
        if v != v:
            return "–"
        return f"{v:.{nd}f}"
    return str(v)


def main():
    qa = json.loads((QA / "qa_report.json").read_text())
    rows = qa["rows"]
    build = json.loads((QA / "build_report_sfx.json").read_text())
    scan = json.loads((QA / "scan.json").read_text())
    man = {e["id"]: e for e in json.loads(MANIFEST.read_text()) if e["category"] in ("sfx", "music")}
    bal = build.get("selection", {}).get("weapons", {}).get("balance", {})
    usd, by_ep, ncalls = spend()
    ids = {r["manifest_id"] for r in rows}
    covered = sorted(i for i in man if i in ids)
    extras = sorted(i for i in ids if i not in man)
    fails = collections.Counter(c for r in rows for c in r["checks_failed"])
    L = []
    L.append(BEGIN)
    L.append("## SFX, ambience and music (WP06_SFX)")
    L.append("")
    L.append("Generated by `Tools/audio/sfx/sfx_review.py` from the pipeline's measurements (`qa_report.py` re-measures "
             "every file on disk). No human listening gate (O4 waived): objective checks plus a machine listen with "
             "`fal-ai/audio-understanding` (match / realism / unwanted sounds per raw take, and a guardrail questionnaire "
             "for every ambience and music take).")
    L.append("")
    L.append("### Summary")
    L.append("")
    tps = [r["true_peak_dbtp"] for r in rows]
    L.append(f"- Manifest `sfx` + `music` entries: **{len(man)}**, all covered ({len(covered)}/{len(man)}); extras not in "
             f"the manifest: {', '.join('`' + e + '`' for e in extras) or 'none'}. Files: **{len(rows)}** "
             "(48 kHz 16-bit WAV; SFX mono, ambience and EL music stereo).")
    L.append(f"- True peak: max {max(tps):.2f} dBTP over all files (limit −1.0). Clipped samples: "
             f"{sum(r['clipped'] for r in rows)}. |DC| > 0.002: {fails.get('dc', 0)} files.")
    est = sum(r["est_download_kb"] for r in rows) / 1000
    L.append(f"- Estimated Web download (AAC 44.1 kHz at the validate_assets kbps assumption): **{est:.1f} MB** for "
             "SFX + ambience + music (VO adds ≈ 5.4–7.7 MB). TECH_PLAN §8.10 plans 18 MB for all audio; see "
             "*Budget* below.")
    L.append(f"- fal spend `WP06SFX`: **${usd:.2f}** in {ncalls} calls ("
             + ", ".join(f"{k.split('/')[-2] if k.count('/') > 1 else k}: ${v:.2f}" for k, v in by_ep.most_common()) + ").")
    L.append(f"- Checks that still fail: " + (", ".join(f"{k} ×{v}" for k, v in fails.most_common()) or "**none**") + ".")
    L.append("")
    # loudness targets
    L.append("### Loudness targets (cue volume 1.0)")
    L.append("")
    L.append("One-shots are levelled by momentary max (400 ms, or 100 ms for short clicks, steps, impacts, shots, UI); "
             "loops and beds by integrated LUFS. Every file is true-peak limited to ≤ −1 dBTP (4× oversampled). The "
             "values are the level a clip has at cue volume 1.0, so layers already sit right against each other "
             "(`LEVELS` in `sfx_process.py`).")
    L.append("")
    L.append("| Category | Target | Metric |")
    L.append("|---|---|---|")
    lv = [("Player weapon stack (transient + body + mech, see below)", "≈ −14 … −16", "100 ms momentary max, peak ≤ −1.2 dBTP"),
          ("Weapon far variants", "−16", "400 ms"), ("Zone tails street / square / interior / desert", "−25 / −26 / −23 / −27", "400 ms, peaks ≤ −12…−14 dBFS"),
          ("Explosions (near / far bake)", "−9 / −13", "400 ms"), ("Bullet cracks / whizzes", "−12 / −17", "100 / 400 ms"),
          ("Impacts", "−16 (soft −19)", "100 ms"), ("Footsteps, foley, handling", "−24", "100 ms"), ("Landing, body fall", "−21", "400 ms"),
          ("Reload parts", "−22", "400 ms"), ("Casings", "−28", "100 ms"), ("Set pieces quiet / normal / loud", "−22 / −19 / −15", "100 / 400 ms"),
          ("Set-piece loops", "−16 … −30 by source", "integrated"), ("UI", "−20", "100 ms"),
          ("Ambience beds", "−22 … −25", "integrated"), ("Music cues / stingers", "−16 / −14", "integrated / 400 ms"),
          ("Procedural music (motif, interval signal, MUS_06)", "−18 … −20", "integrated")]
    for a, b, c in lv:
        L.append(f"| {a} | {b} | {c} |")
    L.append("")
    # weapon layer balance
    if bal:
        L.append("### Weapon layer balance (resume pass 3)")
        L.append("")
        L.append("WeaponShotPlayer plays transient + mech + body + zone tail together at cue volume 1.0 (±1.5 dB jitter on "
                 "transient and body). Pass 2 summed to **+3 … +6.3 dBTP** (each layer was normalised near full scale on its "
                 "own) and the body layer was as loud as the transient. Pass 3: body −10 dB and mech −14 dB under the "
                 "transients (100 ms momentary), the body blooms after the crack (−12 dB for 6 ms), the mech's firing-pin "
                 "click is masked (−24 dB at 0 ms), the tails' first 50 ms are ramped in and their slap-back peaks capped, "
                 "street/interior tails rebuilt from an image-source model, and each transient is limited with a gain curve "
                 "linked to the worst case of every body × mech × tail combination. Auto weapons get their take's own "
                 "slap (> 90 ms) ducked 6 dB and a uniform trim from a simulated 12-round burst at the weapon's RPM.")
        L.append("")
        L.append("| Weapon | Stack 100 ms max (LUFS) | Worst single shot (dBTP) | … with +1.5 dB jitter | Burst max (dBTP) | Burst trim (dB) | <200 Hz share |")
        L.append("|---|---|---|---|---|---|---|")
        for w, v in bal.get("weapons", {}).items():
            L.append(f"| {w} | {fmt(v.get('stack_mmax100_after'))} | {fmt(v.get('worst_stack_tp'), 2)} | "
                     f"{fmt(v.get('worst_stack_tp_jitter'), 2)} | {fmt(v.get('burst_tp_max'), 2)} | {fmt(v.get('burst_trim_db'), 2)} | "
                     f"{fmt(v.get('stack_low200_share'), 2)} |")
        L.append("")
    # guardrails
    L.append("### Guardrails (GDD §2.3, TECH_PLAN §8.7-1)")
    L.append("")
    L.append("Every ambience bed and every music take was asked the guardrail questionnaire (listen.py). Shipped sources "
             "with any *yes* are listed; a *yes* on an ambience take removes it from selection (score −2).")
    L.append("")
    g_rows = [r for r in rows if r.get("guardrail")]
    flagged = [(r, g) for r in g_rows for g in r["guardrail"] if g["yes"]]
    L.append(f"- Shipped files with guardrail answers: {len(g_rows)}; with a *yes*: {len(flagged)}.")
    for r, g in flagged:
        L.append(f"  - `{pathlib.Path(r['file']).name}` ← `{g['src']}`: yes to {g['yes']}")
    # music takes (EL Music v2.5): guardrail questionnaire per take
    sel = json.loads((ROOT / "RawAssets/audio/music/selection.json").read_text())
    shipped = {v["file"] for v in sel.values()}
    mus = []
    for d in sorted((QA / "listen").iterdir()):
        sf, rf = d / "source.txt", d / "result.json"
        if not (sf.exists() and rf.exists()):
            continue
        src = sf.read_text().strip()
        if "/audio/music/" not in src:
            continue
        out = json.loads(rf.read_text()).get("output", "")
        ys = sorted({int(m.group(1)) for m in re.finditer(r"\(?(\d)\)?[^\n(]*?\b(yes)\b", out, flags=re.I)})
        relp = src.split("fun-unity/")[-1]
        mus.append((relp.split("/")[3], relp.split("/")[4], relp in shipped, ys))
    if mus:
        L.append("")
        L.append("Music takes (questions: 1 vocals/singing/spoken, 2 chanting/religious, 3 church bells, 4 regional/ethnic "
                 "scale or instrument, 5 fades out inside the clip; 5 is informational, loops are cut before any outro):")
        L.append("")
        L.append("| Cue | Take | Shipped | Yes to |")
        L.append("|---|---|---|---|")
        for cue, take, shp, ys in sorted(mus):
            L.append(f"| `{cue}` | {take} | {'yes' if shp else 'no'} | {', '.join(map(str, ys)) or 'none'} |")
        L.append("")
    L.append("- Procedural beds use only our own material: `SFX_TV_MUFFLED` (our invented-language Harrou/Legion TTS takes "
             "+ our cassette tune, through a 650 Hz wall low-pass), `SFX_RADIO_TURNED_DOWN` (our `AMB_CASSETTE_TUNE` "
             "through a tiny speaker and a shutter), `AMB_DISTANT_SHOUTING` (our Legion bark takes BK_LEG_01-12 A/B "
             "through a 60-180 m distance chain). No call to prayer, chanting, bells or regional song in any shipped "
             "file; the cassette tune is an instrumental surf-style guitar (not regional).")
    L.append("")
    # loops
    lrows = [r for r in rows if r.get("seam")]
    L.append("### Loop seams")
    L.append("")
    L.append("Seam = wrap of the loop body (samples [lead, lead+body) from `LOOP_POINTS.json`): click ratio (wrap jump vs the "
             "99.9th percentile sample step, < 2.5), 50 ms RMS step and spectral distance across the wrap vs 24 random "
             "interior cut points (p90 + 1 dB). Music loops are judged against their own bar lines.")
    L.append("")
    L.append("| File | Loop (s) | Click ratio | RMS step (dB) | interior p90 | Spectral (dB) | interior p90 | OK |")
    L.append("|---|---|---|---|---|---|---|---|")
    for r in sorted(lrows, key=lambda r: r["file"]):
        s = r["seam"]
        ok = s.get("barline_ok", s["seam_ok"])
        if not ok and r.get("kind") == "synth_loop" and s["click_ratio"] < 2.5:
            ok = "event"   # a tick pattern: the wrap lands in the silence before a tick (no click), RMS step by design
        ip_s = s.get("barline_rms_step_p90_db", s["interior_rms_step_p90_db"])
        ip_f = s.get("barline_spec_p90_db", s["interior_spec_p90_db"])
        L.append(f"| `{pathlib.Path(r['file']).name}` | {fmt(r.get('loop_s'), 2)} | {s['click_ratio']} | {s['seam_rms_step_db']} | "
                 f"{ip_s} | {s['seam_spec_dist_db']} | {ip_f} | {'yes (event loop: wraps in the silence before a tick)' if ok == 'event' else 'yes' if ok else '**no**'} |")
    L.append("")
    # budget
    L.append("### Budget")
    L.append("")
    agg = collections.OrderedDict()
    for r in sorted(rows, key=lambda r: r["folder"]):
        a = agg.setdefault(r["folder"], [0, 0.0, 0.0])
        a[0] += 1
        a[1] += r["dur_s"]
        a[2] += r["est_download_kb"]
    L.append("| Folder | Files | Seconds | Est. download (MB) |")
    L.append("|---|---|---|---|")
    for k, (n, d, kb) in agg.items():
        L.append(f"| `{k}` | {n} | {d:.0f} | {kb / 1000:.2f} |")
    L.append(f"| **Total** | {len(rows)} | {sum(a[1] for a in agg.values()):.0f} | **{est:.2f}** |")
    L.append("")
    L.append("Per-file caps (§8.9) hold: one-shots ≤ 30 KB except where listed under failed checks, ambience loops ≤ 0.45 MB, "
             "music cues ≤ 1.3 MB. The §8.10 line (18 MB for all audio incl. ≈ 300 VO files) is below the sum of its own "
             "per-class caps; the drop list in `Docs/handoff/WP06_SFX.md` frees ≈ 2.6 MB (second variants of stationary beds, P1 bed variants, P2) "
             "if BudgetReport shows no headroom.")
    L.append("")
    # per manifest id table
    L.append("### Per cue")
    L.append("")
    L.append("| Cue | Pri | Files | Seconds | Level (LUFS, metric per category) | Max TP | Machine listen of shipped sources (match/realism, median) | Failed checks |")
    L.append("|---|---|---|---|---|---|---|---|")
    by = collections.defaultdict(list)
    for r in rows:
        by[r["manifest_id"]].append(r)
    bfiles = build.get("files", {})
    for mid in sorted(by):
        rs = by[mid]
        mm, rr = [], []
        for r in rs:
            for s in bfiles.get(r["file"], {}).get("sources", []):
                for l in scan.get(s, {}).get("listen", []):
                    if l.get("kind") == "match" and l.get("match") is not None:
                        mm.append(l["match"])
                        if l.get("realism") is not None:
                            rr.append(l["realism"])
        med = lambda v: sorted(v)[len(v) // 2] if v else None   # noqa: E731
        lvl = [r["mmax100"] if r.get("mmax100") is not None and r["dur_s"] < 1.5 else r["lufs_i"] for r in rs]
        lvl = [v for v in lvl if v is not None and v == v]
        fc = sorted({c for r in rs for c in r["checks_failed"]})
        pri = man.get(mid, {}).get("priority", "extra")
        L.append(f"| `{mid}` | {pri} | {len(rs)} | {sum(r['dur_s'] for r in rs):.1f} | "
                 f"{(fmt(min(lvl)) + ' … ' + fmt(max(lvl))) if lvl else '–'} | {max(r['true_peak_dbtp'] for r in rs):.2f} | "
                 f"{fmt(med(mm), 0)}/{fmt(med(rr), 0)} | {', '.join(fc) or '–'} |")
    L.append("")
    L.append(END)
    text = DOC.read_text()
    block = "\n".join(L)
    if BEGIN in text and END in text:
        text = re.sub(re.escape(BEGIN) + r".*?" + re.escape(END), lambda _m: block, text, flags=re.S)
    else:
        text = text.rstrip("\n") + "\n\n" + block + "\n"
    DOC.write_text(text)
    print("wrote", DOC, len(L), "lines")


if __name__ == "__main__":
    main()
