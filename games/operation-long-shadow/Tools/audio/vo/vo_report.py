#!/usr/bin/env python3
"""Write the VO section of Docs/AUDIO_REVIEW.md (between <!-- VO:BEGIN --> / <!-- VO:END -->) and preview sheets.

  python vo_report.py            # tables from selection.json, verify_report.json, build_report.json, splice report
  python vo_report.py --sheets   # also render RawAssets/audio/vo/previews/*.png (per voice and per chain)
"""
import argparse, json, re, statistics
import numpy as np
from common import ROOT, RAW, TOKENS, VO_OUT, DOCS, load_dialogue, load_manifest, load_casting
from vo_verify import ACCEPTED_SOUNDALIKES
from vo_edit import EDITS
from vo_generate import RESPELL

REVIEW = DOCS / "AUDIO_REVIEW.md"
WEBCHECK = RAW / "webcheck.json"


def fmt(v, nd=2):
    return "–" if v is None else (f"{v:.{nd}f}" if isinstance(v, float) else str(v))


def sheets():
    from vo_preview import sheet
    rep = json.loads((RAW / "build_report.json").read_text())
    dlg = load_dialogue()
    out = RAW / "previews"
    by_voice, by_chain = {}, {}
    for lid, rows in rep.items():
        v = dlg[lid]["voice_id"]
        for r in rows:
            f = ROOT / "RawAssets" / "audio" / "ready" / r["file"]
            by_chain.setdefault(r["chain"], []).append(f)
            if r["chain"] in ("DRY", "BOOTH", "SCRAMBLER", "CLEAN", "PA_HORN", "GREYCOAT_SQUELCH", "HF_AM") and (r["variant"] in (None, "A")):
                by_voice.setdefault(v, []).append(f)
    for v, fs in by_voice.items():
        sheet(out / f"voice_{v}.png", sorted(fs)[:9], cols=3, title=f"{v} (first 9 clips)")
    for c, fs in by_chain.items():
        sheet(out / f"chain_{c}.png", sorted(fs)[:6], cols=3, title=f"chain {c} (first 6 clips)")
    print("sheets ->", out)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--sheets", action="store_true")
    a = ap.parse_args()
    if a.sheets:
        sheets()
    dlg, man, cast = load_dialogue(), load_manifest(), load_casting()
    sel = json.loads((RAW / "selection.json").read_text())
    ver = json.loads((RAW / "verify_report.json").read_text())
    build = json.loads((RAW / "build_report.json").read_text())
    splice = json.loads((RAW / "clockmaker" / "splice_report.json").read_text()) if (RAW / "clockmaker" / "splice_report.json").exists() else {}
    tokc = json.loads((TOKENS / "token_choice.json").read_text()) if (TOKENS / "token_choice.json").exists() else {}
    web = json.loads(WEBCHECK.read_text()) if WEBCHECK.exists() else []
    L = []
    w = L.append
    clips = [r for rows in build.values() for r in rows]
    n_lines = len([l for l in dlg if f"VO_{l}" in man])
    lines_built = len(build)
    w("## VO (WP06_VO)\n")
    w(f"Generated by `Tools/audio/vo/vo_report.py` from the pipeline's own measurements. No human listening gate (O4 waived): "
      f"every take was transcribed with `fal-ai/elevenlabs/speech-to-text/scribe-v2` and checked objectively.\n")
    w("### Summary\n")
    lufs = [r["lufs"] for r in clips]
    tps = [r["true_peak_db"] for r in clips]
    leads = [r["lead_ms"] for r in clips]
    w(f"- Lines in DIALOGUE.json with a manifest entry: **{n_lines}**; lines with shipped clips: **{lines_built}**; clips: **{len(clips)}** "
      f"(+ {len(build)} envelope JSONs).")
    if clips:
        w(f"- Loudness: {min(lufs):.2f} … {max(lufs):.2f} LUFS (target −18 ±1). True peak: max {max(tps):.2f} dBTP (limit −1.0). "
          f"Lead silence: max {max(leads):.0f} ms (limit 60). Clipped samples in shipped files: {sum(r['clipped'] for r in clips)}.")
        dur = sum(r["duration_s"] for r in clips)
        w(f"- Total shipped VO duration: {dur/60:.1f} min. At the import rules (AAC, 22.05/24 kHz mono, quality 60/70) this is roughly "
          f"{dur*6.5/1024:.1f} MB in the build (≈ 6–7 KB/s), against the 18 MB audio budget shared with SFX and music.")
    keys = [k for k in sel if re.sub(r"_[AB]$", "", k) in dlg]
    npass = sum(1 for k in keys if sel[k]["pass"])
    takes = sum(len(v) for v in ver["takes"].values())
    w(f"- Takes generated and verified: {takes} for {len(keys)} take families; families with a fully passing take: {npass}/{len(keys)}.")
    w("- Checks per take: normalised WER vs the line text (numbers expanded, fuzzy match for proper nouns), delivery-tag words spoken "
      "aloud, cut-off (last word missing, or the raw file still loud at its end), clipping in the raw TTS output, speech rate, long "
      "internal gaps, and pitch against the other takes of the same line. Invented-language lines: duration vs syllable count, a "
      "**sound-alike check** (every transcript word is looked up with `wordfreq` in 27 top-20/priority languages; a word with "
      "zipf ≥ 3.2 rejects the take), and letter similarity between transcript and spelling to prefer the take that says what we wrote.")
    aud = json.loads((RAW / "audit.json").read_text())["summary"] if (RAW / "audit.json").exists() else None
    if aud:
        w(f"- **Independent audit** (`Tools/audio/vo/vo_audit.py`, re-measures the files on disk): {aud['clips']}/{aud['expected']} "
          f"expected clips present, {aud['envelopes']} envelopes, {aud['index_rows']} index rows; LUFS {aud['lufs_range'][0]} … "
          f"{aud['lufs_range'][1]}, true peak max {aud['tp_max']} dBTP, lead max {aud['lead_max_ms']:.0f} ms; every file mono 48 kHz "
          f"16-bit; DRY/RADIO (and INTERCOM/RADIO) pairs sample-synchronous; no stale files. Failures: **{len(aud['fails'])}**. "
          f"Estimated build size {aud['est_build_kb']/1024:.1f} MB, {aud['avg_est_kb_per_clip']} KB per clip on average "
          f"(budget ≤ 30 KB average).")
    w("")

    w("### Voice casting confirmation\n")
    w("Median F0 of the chosen takes, spoken lines vs shouted lines (shouting raises F0 by about an octave).\n")
    w("| voice_id | model | voice | settings | takes | median F0 (Hz) | register | result |")
    w("|---|---|---|---|---|---|---|---|")
    vf = ver.get("voice_f0_median", {})
    for vid, c in cast.items():
        if not vid.startswith("vo_"):
            continue
        model = c["endpoint"]
        if vid == "vo_legion":
            voice = "A: George (seed 31), B: Daniel (seed 32)"
            f0 = f"A {fmt(vf.get('vo_legion_A'),0)} / B {fmt(vf.get('vo_legion_B'),0)}"
        else:
            voice = c["voice"]
            f0 = fmt(vf.get(vid), 0)
        settings = (f"stability {c['stability']}, similarity {c['similarity_boost']}" + (f", seed {c['seed']}" if c.get("seed") else "")) if c["engine"] == "el" else "style_instructions (casting.json)"
        nt = sum(len(v) for k, v in ver["takes"].items() if dlg[re.sub(r'_[AB]$', '', k)]["voice_id"] == vid)
        if vid == "vo_clockmaker":
            nt = f"{sum(1 for _ in TOKENS.glob('*/take_*'))} token takes"
            tf = [t["f0"] for r in tokc.get("report", {}).values() for t in r["takes"] if t.get("f0")]
            f0 = fmt(float(np.median(tf)), 0) if tf else "–"
        elif vid != "vo_legion":
            sp, sh = [], []
            for k, v in ver["takes"].items():
                l = dlg[re.sub(r'_[AB]$', '', k)]
                if l["voice_id"] != vid or k not in sel:
                    continue
                t = next((t for t in v if t["take"] == sel[k]["take"]), None)
                if t and t.get("f0_med"):
                    (sh if "shout" in l["delivery"] else sp).append(t["f0_med"])
            f0 = f"{fmt(float(np.median(sp)), 0) if sp else '–'} spoken" + (f" / {fmt(float(np.median(sh)), 0)} shouted" if sh else "")
        reg = {"vo_sparrow": "female alto", "vo_clockmaker": "female"}.get(vid, "male")
        w(f"| `{vid}` | `{model}` | {voice} | {settings} | {nt} | {f0} | {reg} | locked |")
    w("\nGemini voices were confirmed from their first takes by pitch (Kore and Erinome in the female range, Fenrir, Algenib, Algieba "
      "and Iapetus in the male range) and by transcript. Legion shouting reads a high F0 (shouted register), as expected. "
      "The Greycoat median sits at the 60 Hz search floor: Iapetus is very low and partly creaky in this clipped delivery. "
      "Timbre consistency was also checked per voice (MFCC mean/std distance of every chosen take to the voice centroid): the only "
      "outliers are the shouted callouts and the whispered/telephone lines, i.e. delivery, not a different voice.\n")

    w("### Guardrails\n")
    w("**Invented-word web check (O3, GDD §2.3-5).** Every word of the Legion cant, Greyspeak and Sardani PA lines was searched "
      "(Wiktionary/dictionary hits). Rule: reject a common word in a priority language (Arabic, Persian, Turkish, Hebrew, Kurdish, "
      "Slavic), in a top-20 world language, or anything religious; minor-language collisions pass with a note.\n")
    if web:
        w("| word | line(s) | finding | verdict |")
        w("|---|---|---|---|")
        for r in web:
            w(f"| {r['word']} | {r['lines']} | {r['finding']} | **{r['verdict']}** |")
    w("\n**Sounds like real speech?** Scribe transcripts of the chosen bark takes (auto language detection):\n")
    w("Rejected takes are listed per line with the real word Scribe heard; the shipped take is the one in the table. "
      "Reviewed exceptions (accepted sound-alikes): " + "; ".join(f"`{k}`: {v}" for k, v in ACCEPTED_SOUNDALIKES.items()) + ".\n")
    w("| line | voice | text | shipped take: transcript | detected language | letter sim. | takes rejected as sound-alikes |")
    w("|---|---|---|---|---|---|---|")
    for k in sorted(keys):
        lid = re.sub(r"_[AB]$", "", k)
        if not (lid.startswith("BK_") or lid == "D012"):
            continue
        t = next((t for t in ver["takes"][k] if t["take"] == sel[k]["take"]), None)
        if not t:
            continue
        tr = (t.get("transcript") or "").strip()
        rej = sorted({w_ for x in ver["takes"][k] for i in x["issues"] if i.startswith("sounds_like_real_word:")
                      for w_ in i.split(":", 1)[1].split(",")})
        w(f"| {lid} | {k[-1] if k != lid else dlg[lid]['voice_id'].replace('vo_','')} | {dlg[lid]['text']} | t{t['take']}: {tr} | "
          f"{t.get('stt_lang')} | {fmt(t.get('phon_sim'))} | {', '.join(rej) if rej else '–'} |")
    w("\n- **No religious audio:** VO is speech only; no chanting, singing or call to prayer appears in any prompt or take; the "
      "Sardani PA line no longer contains `om` (sacred syllable).")
    w("- **No caricatured accents:** accents are never put in ElevenLabs tags; Gemini styles ask for a faint, natural accent that is "
      "never exaggerated. Objective proxy only (no listening gate): speech rate and pitch of every chosen take are within the "
      "ranges of the same voice's other lines.")
    w("- **Delivery tags never spoken:** every chosen take's transcript was scanned for tag words that are not in the line.\n")

    w("### Take edits and respellings (no change to the line text)\n")
    for key, (keep, reason) in EDITS.items():
        w(f"- `{key}`: kept the first {keep} words of the take (`Tools/audio/vo/vo_edit.py`, cut by Scribe word timestamps, "
          f"re-transcribed afterwards). {reason}.")
    w("- `D082`: cut 30 ms after the last word (delivery \"cut off\"), in `vo_build.py`.")
    for (lid, v), r in RESPELL.items():
        w(f"- `{lid}` voice {v}: TTS-only respellings {', '.join(f'take {t}+: \"{x}\"' for t, x in sorted(r.items()))} because every "
          f"take of the lexicon spelling was heard as an English word; the shipped take is the one in the bark table.")
    w("- FAR (and one BOOTH) clips whose quiet head (a low-passed fricative onset, a soft inhale) exceeded 60 ms were trimmed to "
      "45 ms before the first loud frame (`enforce_lead`); DRY/RADIO/INTERCOM are never trimmed separately so the crossfade "
      "pairs stay sample-synchronous.\n")
    w("### Clockmaker splices\n")
    if tokc:
        w("Token takes chosen (`Tools/audio/vo/clockmaker_splice.py pick`): " + ", ".join(f"{k}=take {v}" for k, v in sorted(tokc["choice"].items())) + ".\n")
    if splice:
        w("| line | chain | tokens | grid | duration (s) | LUFS | TP | STT of the dry splice |")
        w("|---|---|---|---|---|---|---|---|")
        for lid, r in sorted(splice.items()):
            stf = RAW / "clockmaker" / f"stt_{lid}" / "result.json"
            tr = json.loads(stf.read_text()).get("text", "") if stf.exists() else "–"
            w(f"| {lid} | {r['chain']} | {r['slots']} | {r['grid_s']} s | {r['dur']} | {r['lufs']} | {r['true_peak_db']} | {tr} |")
        w("\n`D039` must be 13.5 s ± 0.2 (15 slots × 0.9 s + 30 ms lead). `D066` is cut mid-word into static and capped at 2.2 s. "
      "Tokens longer than 0.86 s (\"Attention\" 1.03 s, \"Sundial\" 1.08 s, \"Zero\") are shortened with WSOLA time-scaling "
      "(pitch unchanged) to fit their slot. The basement loop source (`NUM_BASEMENT_LOOP`, music, owned by WP06_SFX) is rendered "
      "from the same tokens as a seamless 66 s loop at `RawAssets/audio/vo/clockmaker/NUM_BASEMENT_LOOP_from_tokens.wav`.\n")

    w("### Per-line metrics\n")
    w("WER is for the chosen take (– for invented-language lines and splices). One row per shipped clip.\n")
    w("| clip | take | pass/takes | WER | dur (s) | LUFS | TP (dBTP) | lead (ms) | notes |")
    w("|---|---|---|---|---|---|---|---|---|")
    for lid in dlg:
        if lid not in build:
            continue
        for r in build[lid]:
            k = lid if not r["variant"] else f"{lid}_{r['variant']}"
            s = sel.get(k, {})
            notes = "; ".join(s.get("issues", [])) or ""
            if s.get("note"):
                notes = (notes + "; " if notes else "") + s["note"]
            if isinstance(r["take"], int) and r["take"] > 100:
                notes = (notes + "; " if notes else "") + f"edit of take {r['take'] - 100} (first words kept)"
            pt = f"{s.get('n_pass','–')}/{s.get('n_takes','–')}" if s else "splice"
            w(f"| {r['clip']} | {r['take']} | {pt} | {fmt(s.get('wer'))} | {r['duration_s']:.2f} | {r['lufs']:.2f} | {r['true_peak_db']:.2f} | {r['lead_ms']:.0f} | {notes} |")
    text = "\n".join(L) + "\n"
    body = REVIEW.read_text() if REVIEW.exists() else "# Audio review\n\nObjective audio checks per WP06 package (O4: no human listening gate).\n\n"
    block = "<!-- VO:BEGIN -->\n" + text + "<!-- VO:END -->"
    if "<!-- VO:BEGIN -->" in body:
        body = re.sub(r"<!-- VO:BEGIN -->.*?<!-- VO:END -->", lambda m: block, body, flags=re.S)
    else:
        body = body.rstrip() + "\n\n" + block + "\n"
    REVIEW.write_text(body)
    print("wrote", REVIEW, len(L), "lines")


if __name__ == "__main__":
    main()
